import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import babel from "@rollup/plugin-babel";
import resolve from "@rollup/plugin-node-resolve";
import { rollup } from "rollup";

const packageRoot = new URL("../packages/tool-definitions/", import.meta.url);

const bundle = await rollup({
  input: fileURLToPath(new URL("src/index.ts", packageRoot)),
  plugins: [
    resolve({ extensions: [".ts", ".js", ".json"] }),
    babel({
      babelHelpers: "bundled",
      extensions: [".ts", ".js"],
      presets: ["@babel/preset-typescript"],
    }),
  ],
});

try {
  const { output } = await bundle.generate({ format: "es" });
  const { toolDefinitions } = await import(
    `data:text/javascript;base64,${Buffer.from(output[0].code).toString("base64")}`
  );
  // Emit only metadata and Zod schemas; never ship factory or execution code.
  const definitions = Object.entries(toolDefinitions).map(([key, tool]) =>
    `${JSON.stringify(key)}: {\nname: ${JSON.stringify(tool.name)},\n` +
    `description: ${JSON.stringify(tool.description)},\nparameters: z.fromJSONSchema(${JSON.stringify(tool.parameters, null, 2)})\n}`
  );
  const code = `// Generated by npm run build:tool-definitions. Do not edit.\n` +
    `import { z } from "zod";\n\n` +
    `export const toolDefinitions = {\n${definitions.join(",\n")}\n};\n\n` +
    `export const { ${Object.keys(toolDefinitions).map((key) =>
      `${JSON.stringify(key)}: ${key.replaceAll("-", "_")}`
    ).join(", ")} } = toolDefinitions;\n` +
    `export const tools = Object.values(toolDefinitions);\n` +
    `export default toolDefinitions;\n`;
  await mkdir(new URL("dist/", packageRoot), { recursive: true });
  await writeFile(new URL("dist/index.js", packageRoot), code);
  console.log("[build-tool-definitions] packages/tool-definitions/dist/index.js");
} finally {
  await bundle.close();
}
