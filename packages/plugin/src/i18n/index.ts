export type PluginLocale = "zh" | "en";

type Message = Record<PluginLocale, string>;

/**
 * Keep the plugin aligned with the editor host's lightweight language contract.
 * The host sets `window.__lang_type__` before the plugin is rendered.
 */
export function getPluginLocale(): PluginLocale {
  if (typeof window === "undefined") return "zh";
  const locale = (window as Window & { __lang_type__?: unknown }).__lang_type__;
  return typeof locale === "string" && locale.toLowerCase().startsWith("en") ? "en" : "zh";
}

export function i18n(messages: Message): string {
  return messages[getPluginLocale()] ?? messages.zh;
}

